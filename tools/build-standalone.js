#!/usr/bin/env node
/* ============================================================
   Build qoix-standalone.html
   ============================================================
   Inlines styles.css and every js/*.js referenced by index.html
   into a single self-contained file that runs from a file:// URL
   or any static host with no build step.

   The repo previously carried a hand-maintained standalone copy
   that had already drifted out of sync with js/. Generating it
   means it cannot drift again.

       npm run standalone
   ============================================================ */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT  = path.join(ROOT, 'qoix-standalone.html');

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8');
}

// A closing </script> anywhere inside inlined JS would end the block early.
function escapeForScriptBlock(js) {
  return js.replace(/<\/script>/gi, '<\\/script>');
}

function main() {
  let html = read('index.html');

  // Inline the stylesheet.
  html = html.replace(
    /<link\s+rel="stylesheet"\s+href="styles\.css"\s*\/?>/i,
    () => `<style>\n${read('styles.css')}\n</style>`
  );

  // Inline every local script, in the order index.html declares them.
  const scriptTag = /<script\s+src="((?:js\/)[^"]+)"\s*><\/script>/gi;
  const inlined = [];
  html = html.replace(scriptTag, (_m, src) => {
    inlined.push(src);
    return `<script>\n/* ===== ${src} ===== */\n${escapeForScriptBlock(read(src))}\n</script>`;
  });

  if (!inlined.length) {
    console.error('No <script src="js/…"> tags found in index.html — nothing was inlined.');
    process.exit(1);
  }

  // The CSP in index.html forbids inline script, which is exactly right
  // for the multi-file app but would block the bundle. Relax only that
  // directive for the standalone build.
  html = html.replace(/script-src 'self'/, "script-src 'self' 'unsafe-inline'");

  const banner = `<!--\n  QOIX Synthesizer — single-file build\n` +
                 `  GENERATED by tools/build-standalone.js. Do not edit by hand;\n` +
                 `  edit index.html / styles.css / js/*.js and re-run \`npm run standalone\`.\n-->\n`;
  html = html.replace(/^<!DOCTYPE html>\s*/i, m => m + banner);

  fs.writeFileSync(OUT, html, 'utf8');
  const kb = (Buffer.byteLength(html) / 1024).toFixed(0);
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${kb} KB) — inlined styles.css + ${inlined.length} scripts:`);
  inlined.forEach(s => console.log(`  · ${s}`));
}

main();
